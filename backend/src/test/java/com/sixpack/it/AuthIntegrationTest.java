package com.sixpack.it;

import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.verify;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.multipart;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import com.sixpack.storage.TestImages;
import com.sixpack.user.domain.MailSender;
import java.util.Map;
import org.junit.jupiter.api.Test;
import org.mockito.ArgumentCaptor;
import org.springframework.http.MediaType;
import org.springframework.mock.web.MockMultipartFile;
import org.springframework.test.context.bean.override.mockito.MockitoBean;

class AuthIntegrationTest extends IntegrationTest {

    @MockitoBean
    MailSender mailSender;

    @Test
    void registerWithPhotoReturnsTokenAndNeverThePassword() throws Exception {
        mvc.perform(multipart("/api/v1/user/register")
                        .file(new MockMultipartFile("photo", "me.png", "image/png", TestImages.png()))
                        .param("name", "Asha").param("email", "Asha@Example.com").param("password", "password123")
                        .param("gender", "female").param("dob", "1999-02-03"))
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.success").value(true))
                .andExpect(jsonPath("$.token").isNotEmpty())
                .andExpect(jsonPath("$.user.email").value("asha@example.com"))
                .andExpect(jsonPath("$.user.role").value("user"))
                .andExpect(jsonPath("$.user.photo").value(org.hamcrest.Matchers.startsWith("uploads/")))
                .andExpect(jsonPath("$.user.password").doesNotExist());
    }

    @Test
    void duplicateAndInvalidRegistrationsAreRejected() throws Exception {
        register("dup@test.dev");
        mvc.perform(multipart("/api/v1/user/register").param("name", "X").param("email", "dup@test.dev")
                        .param("password", "password123").param("gender", "male").param("dob", "2000-01-01"))
                .andExpect(status().isConflict());
        mvc.perform(multipart("/api/v1/user/register").param("name", "X").param("email", "short@test.dev")
                        .param("password", "short").param("gender", "male").param("dob", "2000-01-01"))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.message").value(org.hamcrest.Matchers.containsString("password")));
    }

    @Test
    void loginAndMe() throws Exception {
        register("login@test.dev");
        mvc.perform(post("/api/v1/user/login").contentType(MediaType.APPLICATION_JSON)
                        .content("{\"email\":\"login@test.dev\",\"password\":\"wrong-password\"}"))
                .andExpect(status().isUnauthorized())
                .andExpect(jsonPath("$.success").value(false));
        String token = body(mvc.perform(post("/api/v1/user/login").contentType(MediaType.APPLICATION_JSON)
                        .content("{\"email\":\"login@test.dev\",\"password\":\"password123\"}"))
                .andExpect(status().isOk()).andReturn()).get("token").asText();
        mvc.perform(get("/api/v1/user/me")).andExpect(status().isUnauthorized());
        mvc.perform(get("/api/v1/user/me").header("Authorization", bearer(token)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.user.email").value("login@test.dev"));
    }

    @Test
    void legacyUserWithNodeBcryptHashCanLogIn() throws Exception {
        // Document shaped like the old Mongoose model; hash generated by node `bcrypt.hash("legacy-pass", 10)`.
        mongo.getCollection("users").insertOne(new org.bson.Document()
                .append("name", "Legacy").append("email", "legacy@test.dev")
                .append("password", "$2b$10$Tn6i.ynqKLyP3kXR5Jzje.b6IApynXF8TdZgKoKbCRtwOKgQXdZnC")
                .append("photo", "uploads/old.jpg").append("role", "user").append("gender", "male")
                .append("dob", java.util.Date.from(java.time.Instant.parse("1996-01-01T00:00:00Z")))
                .append("__v", 0));
        mvc.perform(post("/api/v1/user/login").contentType(MediaType.APPLICATION_JSON)
                        .content("{\"email\":\"legacy@test.dev\",\"password\":\"legacy-pass\"}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.user.dob").value("1996-01-01"));
    }

    @Test
    void passwordResetIsTokenBasedAndSingleUse() throws Exception {
        register("reset@test.dev");

        // The old takeover request (email + new password, no token) must not work.
        mvc.perform(post("/api/v1/user/reset-password").contentType(MediaType.APPLICATION_JSON)
                        .content("{\"email\":\"reset@test.dev\",\"password\":\"hacked-password\"}"))
                .andExpect(status().isBadRequest());

        // Unknown emails get the same response (no account enumeration) and no mail.
        mvc.perform(post("/api/v1/user/forgot-password").contentType(MediaType.APPLICATION_JSON)
                .content("{\"email\":\"nobody@test.dev\"}")).andExpect(status().isOk());

        mvc.perform(post("/api/v1/user/forgot-password").contentType(MediaType.APPLICATION_JSON)
                .content("{\"email\":\"reset@test.dev\"}")).andExpect(status().isOk());
        ArgumentCaptor<String> link = ArgumentCaptor.forClass(String.class);
        verify(mailSender).sendPasswordReset(eq("reset@test.dev"), anyString(), link.capture());
        String token = link.getValue().substring(link.getValue().indexOf("token=") + 6);

        String reset = json.writeValueAsString(Map.of("token", token, "password", "brand-new-password"));
        mvc.perform(post("/api/v1/user/reset-password").contentType(MediaType.APPLICATION_JSON).content(reset))
                .andExpect(status().isOk());
        mvc.perform(post("/api/v1/user/reset-password").contentType(MediaType.APPLICATION_JSON).content(reset))
                .andExpect(status().isBadRequest());
        mvc.perform(post("/api/v1/user/login").contentType(MediaType.APPLICATION_JSON)
                        .content("{\"email\":\"reset@test.dev\",\"password\":\"brand-new-password\"}"))
                .andExpect(status().isOk());
    }
}
